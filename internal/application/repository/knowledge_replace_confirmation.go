package repository

import (
	"context"
	"database/sql"
	"errors"
	"time"

	"github.com/Tencent/WeKnora/internal/types"
	"gorm.io/gorm"
)

// ErrKnowledgeReplacementUnconfirmed means the new file may already be referenced by a committed row.
var ErrKnowledgeReplacementUnconfirmed = errors.New("knowledge replacement commit could not be confirmed")

// KnowledgeReplacementWriter atomically replaces a fetched ordinary file and its original input.
type KnowledgeReplacementWriter interface {
	ReplaceKnowledgeWithInput(
		context.Context, *types.Knowledge, *types.Knowledge, []string, any,
	) (*types.KnowledgeBuildInputProof, error)
}

type knowledgeReplacementAttemptKey struct{}

// This witness exists only for the synchronous SQL call that retires before and
// creates after. Neither client metadata nor a later caller can mint one by ID.
type knowledgeReplacementAttempt struct {
	ctx                                context.Context
	beforeID, beforeChannel, afterRoot string
	beforeVersion                      time.Time
	store                              *KnowledgeInputProvenanceStore
	sourceType                         string
	proof                              *types.KnowledgeBuildInputProof
}

// ReplaceKnowledgeWithConfirmedInput can recover a lost acknowledgement using only
// the admission generated by this specific write, even if another writer ingests identical bytes.
func ReplaceKnowledgeWithConfirmedInput(ctx context.Context, writer KnowledgeReplacementWriter,
	before, after *types.Knowledge, tags []string, artifact []byte,
) (*types.KnowledgeBuildInputProof, error) {
	if ctx == nil || writer == nil || invalidKnowledgeReplacement(before, after) {
		return nil, ErrKnowledgeInputChanged
	}
	root, err := knowledgeRootDigest(after)
	if err != nil {
		return nil, err
	}
	attempt := &knowledgeReplacementAttempt{
		beforeID: before.ID, beforeChannel: before.Channel, beforeVersion: before.UpdatedAt, afterRoot: root,
	}
	attempt.ctx = context.WithValue(ctx, knowledgeReplacementAttemptKey{}, attempt)
	proof, err := writer.ReplaceKnowledgeWithInput(attempt.ctx, before, after, tags, artifact)
	if err == nil || attempt.proof == nil {
		return proof, err
	}
	readCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 10*time.Second)
	defer cancel()
	if confirmErr := attempt.confirm(readCtx, artifact); confirmErr != nil {
		return nil, errors.Join(err, ErrKnowledgeReplacementUnconfirmed, confirmErr)
	}
	return attempt.proof, nil
}

// Compare the intended target before GORM applies its creation defaults. The
// admission independently seals the resulting normalized, persisted record.
func matchingKnowledgeReplacementAttempt(ctx context.Context,
	before, after *types.Knowledge,
) *knowledgeReplacementAttempt {
	a, ok := ctx.Value(knowledgeReplacementAttemptKey{}).(*knowledgeReplacementAttempt)
	if !ok || a.ctx != ctx || a.beforeID != before.ID || a.beforeChannel != before.Channel ||
		!a.beforeVersion.Equal(before.UpdatedAt) {
		return nil
	}
	root, err := knowledgeRootDigest(after)
	if err != nil || root != a.afterRoot {
		return nil
	}
	return a
}

func (a *knowledgeReplacementAttempt) confirm(ctx context.Context, artifact []byte) error {
	if err := KnowledgeInputArtifactMatches(a.proof, artifact); err != nil {
		return err
	}
	if err := CheckScopedOnboardingConfigurationReads(ctx); err != nil {
		return err
	}
	if _, nested := a.store.db.Statement.ConnPool.(gorm.TxCommitter); nested {
		return ErrKnowledgeInputChanged
	}
	options := &sql.TxOptions{}
	switch a.store.db.Name() {
	case "postgres":
		options.Isolation = sql.LevelRepeatableRead
	case "sqlite":
	default:
		return ErrKnowledgeInputChanged
	}
	return a.store.db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		snapshot, err := a.store.captureKnowledgeBuildSnapshotInTx(tx, types.KnowledgeBuildInputCaptureRequest{
			TenantID: a.proof.TenantID, KnowledgeBaseID: a.proof.KnowledgeBaseID, KnowledgeID: a.proof.KnowledgeID,
			Expected: a.proof,
		}, false)
		if err != nil {
			return err
		}
		sourceType, err := registeredOrdinaryReplacementType(tx, snapshot.Knowledge)
		if err != nil {
			return err
		}
		if sourceType != a.sourceType {
			return ErrKnowledgeInputChanged
		}
		return nil
	}, options)
}
